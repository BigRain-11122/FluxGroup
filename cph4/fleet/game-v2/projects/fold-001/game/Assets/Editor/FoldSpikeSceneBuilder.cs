using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Text;
using System.Text.RegularExpressions;
using UnityEditor;
using UnityEditor.SceneManagement;
using UnityEngine;
using UnityEngine.SceneManagement;

namespace FoldSpike.Editor
{
    // Builds the Fold spike scene from the README component table and runs ReplayHarness once,
    // writing machine-readable numbers to Logs/replay_result.json. Editor-only: it never ships.
    public static class FoldSpikeSceneBuilder
    {
        const string SceneDir = "Assets/Scenes";
        const string ScenePath = "Assets/Scenes/FoldSpike.unity";
        const string MaterialDir = "Assets/Materials";
        const string MaterialPath = "Assets/Materials/FoldPaper.mat";
        const string ResultJsonRel = "Logs/replay_result.json";
        const string ReplayObjectName = "FoldSpike";

        [MenuItem("FoldSpike/Build And Run")]
        public static void BuildAndRun()
        {
            string projectRoot = Path.GetDirectoryName(Application.dataPath);
            string resultPath = Path.Combine(projectRoot, ResultJsonRel);
            Directory.CreateDirectory(Path.GetDirectoryName(resultPath));

            try
            {
                SceneRefs refs = BuildScene();
                SaveScene();

                ReplayNumbers numbers = RunReplay(refs);

                // The negative control must separate a correct fold from an unfolded sheet. If it
                // does not, the shape numbers above mean nothing and no downstream decision may
                // consume them - fail the batch instead of reporting a green verdict.
                if (!numbers.GateLive)
                {
                    InvalidOperationException dead = new InvalidOperationException(
                        "negative control did not separate folded from unfolded; shape verdict is not evidence");
                    WriteResult(resultPath, numbers, dead);
                    Debug.LogError("[FoldSpike] " + dead.Message + "\n" + numbers.Report);
                    throw dead;
                }

                WriteResult(resultPath, numbers, null);

                Debug.Log("[FoldSpike] replay_result.json -> " + resultPath);
                Debug.Log("[FoldSpike] REPORT\n" + numbers.Report);
            }
            catch (Exception ex)
            {
                Debug.LogError("[FoldSpike] BuildAndRun failed: " + ex);
                WriteResult(resultPath, null, ex);
                // Rethrow so batchmode exits non-zero instead of reporting a silent success.
                throw;
            }
        }

        struct SceneRefs
        {
            public FoldController Controller;
            public DrawerController Drawer;
            public ReplayHarness Harness;
            public Camera Cam;
        }

        struct ReplayNumbers
        {
            public bool Consistent;
            public bool CoveragePass;
            public bool CoveragePerfect;
            public bool GateLive;
            public string Verdict;
            public double Coverage;
            public double Iou;
            public double NcFoldedIou;
            public double NcUnfoldedIou;
            public double NcUnfoldedCov;
            public double NcWrongSideIou;
            public double MinMs;
            public double P50Ms;
            public double MaxMs;
            public bool DrawerPlace;
            public bool DrawerReject;
            public string Report;
        }

        // README section 3/4: camera + paper + drawer slots, one root carrying the three
        // MonoBehaviour systems. CoverageJudge is a plain C# class (ReplayHarness owns one),
        // so it cannot be attached as a component.
        static SceneRefs BuildScene()
        {
            EnsureAssetFolder(SceneDir);

            Scene scene = EditorSceneManager.NewScene(NewSceneSetup.EmptyScene, NewSceneMode.Single);

            // --- Camera ---
            GameObject camGo = new GameObject("Main Camera");
            camGo.tag = "MainCamera";
            Camera cam = camGo.AddComponent<Camera>();
            cam.orthographic = true;
            cam.orthographicSize = 0.5f;
            cam.nearClipPlane = 0.1f;
            cam.farClipPlane = 100f;
            cam.clearFlags = CameraClearFlags.SolidColor;
            cam.backgroundColor = new Color(0.10f, 0.10f, 0.12f, 1f);
            camGo.transform.position = new Vector3(0f, 0f, -10f);
            camGo.transform.rotation = Quaternion.identity;

            // --- Paper render surface (mesh is generated by FoldController.Initialize) ---
            GameObject paperGo = new GameObject("Paper");
            MeshFilter paperFilter = paperGo.AddComponent<MeshFilter>();
            MeshRenderer paperRenderer = paperGo.AddComponent<MeshRenderer>();
            Material paperMaterial = EnsureMaterial();
            if (paperMaterial != null) paperRenderer.sharedMaterial = paperMaterial;
            paperGo.transform.position = Vector3.zero;

            // --- Root with the systems ---
            GameObject root = new GameObject(ReplayObjectName);
            FoldController controller = root.AddComponent<FoldController>();
            DrawerController drawer = root.AddComponent<DrawerController>();
            ReplayHarness harness = root.AddComponent<ReplayHarness>();

            // --- Drawer slots: 6 anchors in a row (README: x -0.45..0.45, y -0.55) ---
            GameObject drawerGo = new GameObject("Drawer");
            drawerGo.transform.SetParent(root.transform, false);
            Transform[] slots = new Transform[DrawerController.SlotCount];
            for (int i = 0; i < DrawerController.SlotCount; i++)
            {
                GameObject slot = new GameObject("Slot" + i);
                slot.transform.SetParent(drawerGo.transform, false);
                float x = (i - (DrawerController.SlotCount - 1) * 0.5f) * 0.18f;
                slot.transform.localPosition = new Vector3(x, -0.55f, 0f);
                slots[i] = slot.transform;
            }
            drawer.Slots = slots;
            drawer.SlotPitch = 0.18f;

            // --- FoldController wiring (README table) ---
            controller.Cam = cam;
            controller.PaperMeshFilter = paperFilter;
            controller.PaperWidth = 1.0f;
            controller.PaperHeight = 0.7f;
            controller.SnapScreenPercent = 0.03f;
            controller.MinCommitAngle = 25.0f;
            controller.SettleSeconds = 0.15f;
            controller.UseLegacyInput = true;
            controller.Candidates = new List<CandidateFold>
            {
                MakeCandidate(0.00f, -0.35f, 0.00f, 0.35f, true),   // index 0 must be the solution
                MakeCandidate(-0.18f, -0.35f, 0.18f, 0.35f, false),
                MakeCandidate(-0.50f, 0.12f, 0.50f, 0.12f, false)
            };

            // --- Harness wiring ---
            harness.Controller = controller;
            harness.Drawer = drawer;
            harness.RepeatCount = 20;
            harness.RunOnStart = false;
            harness.TargetOutline = null; // empty => left-half silhouette (README section 5)

            EditorUtility.SetDirty(controller);
            EditorUtility.SetDirty(drawer);
            EditorUtility.SetDirty(harness);
            EditorSceneManager.MarkSceneDirty(scene);

            SceneRefs refs = new SceneRefs();
            refs.Controller = controller;
            refs.Drawer = drawer;
            refs.Harness = harness;
            refs.Cam = cam;
            return refs;
        }

        static CandidateFold MakeCandidate(float ax, float ay, float bx, float by, bool isSolution)
        {
            CandidateFold c = new CandidateFold();
            c.a = new Vector2(ax, ay);
            c.b = new Vector2(bx, by);
            c.isSolution = isSolution;
            return c;
        }

        static void SaveScene()
        {
            Scene active = EditorSceneManager.GetActiveScene();
            bool saved = EditorSceneManager.SaveScene(active, ScenePath);
            if (!saved)
            {
                throw new InvalidOperationException("Scene save returned false for " + ScenePath);
            }
            AssetDatabase.SaveAssets();
            Debug.Log("[FoldSpike] scene saved: " + ScenePath);
        }

        // Activates the runtime graph the way Awake would, then runs the public replay entry point.
        static ReplayNumbers RunReplay(SceneRefs refs)
        {
            if (refs.Controller == null || refs.Harness == null)
            {
                throw new InvalidOperationException("scene references missing");
            }

            refs.Controller.Initialize();

            if (refs.Controller.Paper == null)
            {
                throw new InvalidOperationException("FoldController.Paper not initialised");
            }

            refs.Harness.Run();

            string report = refs.Harness.LastReport ?? string.Empty;
            if (report.Length == 0)
            {
                throw new InvalidOperationException("ReplayHarness produced no report");
            }

            ReplayNumbers n = new ReplayNumbers();
            n.Report = report;

            Match consistent = Regex.Match(report, @"consistent=(YES|NO)");
            n.Consistent = refs.Harness.LastConsistent
                           && consistent.Success
                           && consistent.Groups[1].Value == "YES";

            Match shape = Regex.Match(report, @"shape\s*=\s*(.+?)\s+cov=([0-9.]+)");
            if (shape.Success)
            {
                n.Verdict = shape.Groups[1].Value.Trim();
                n.Coverage = ParseDouble(shape.Groups[2].Value);
            }
            else
            {
                n.Verdict = "UNKNOWN";
                n.Coverage = -1.0;
            }
            n.CoveragePass = n.Verdict == "PASS" || n.Verdict == "PERFECT";
            n.CoveragePerfect = n.Verdict == "PERFECT";

            // \b keeps this from matching the folded_iou= field inside the control line.
            Match iou = Regex.Match(report, @"\biou=([0-9.]+)");
            n.Iou = iou.Success ? ParseDouble(iou.Groups[1].Value) : -1.0;

            Match ctl = Regex.Match(report,
                @"ctl\s*=\s*folded_iou=([0-9.]+)\s+unfolded_iou=([0-9.]+)\s+"
                + @"unfolded_cov=([0-9.]+)\s+wrongside_iou=([0-9.]+)\s+live=(YES|NO)");
            if (ctl.Success)
            {
                n.NcFoldedIou = ParseDouble(ctl.Groups[1].Value);
                n.NcUnfoldedIou = ParseDouble(ctl.Groups[2].Value);
                n.NcUnfoldedCov = ParseDouble(ctl.Groups[3].Value);
                n.NcWrongSideIou = ParseDouble(ctl.Groups[4].Value);
                n.GateLive = ctl.Groups[5].Value == "YES";
            }
            else
            {
                n.NcFoldedIou = n.NcUnfoldedIou = n.NcUnfoldedCov = n.NcWrongSideIou = -1.0;
                n.GateLive = false;
            }

            Match ms = Regex.Match(report, @"ms\s*=\s*([0-9.]+)\s*/\s*([0-9.]+)\s*/\s*([0-9.]+)");
            if (ms.Success)
            {
                n.MinMs = ParseDouble(ms.Groups[1].Value);
                n.P50Ms = ParseDouble(ms.Groups[2].Value);
                n.MaxMs = ParseDouble(ms.Groups[3].Value);
            }
            else
            {
                n.MinMs = n.P50Ms = n.MaxMs = -1.0;
            }

            Match placed = Regex.Match(report, @"placed6=(True|False)");
            n.DrawerPlace = placed.Success && placed.Groups[1].Value == "True";
            Match rejected = Regex.Match(report, @"rejected7=(True|False)");
            n.DrawerReject = rejected.Success && rejected.Groups[1].Value == "True";

            return n;
        }

        static double ParseDouble(string raw)
        {
            double v;
            if (double.TryParse(raw, NumberStyles.Float, CultureInfo.InvariantCulture, out v)) return v;
            if (double.TryParse(raw, NumberStyles.Float, CultureInfo.CurrentCulture, out v)) return v;
            return -1.0;
        }

        static void WriteResult(string path, ReplayNumbers? numbers, Exception error)
        {
            StringBuilder sb = new StringBuilder();
            sb.Append("{\n");
            sb.Append("  \"status\": \"").Append(error == null ? "OK" : "FAIL").Append("\",\n");
            sb.Append("  \"generated_at\": \"").Append(DateTime.Now.ToString("yyyy-MM-ddTHH:mm:ss", CultureInfo.InvariantCulture)).Append("\",\n");
            sb.Append("  \"engine\": \"2022.3.62t17\",\n");
            sb.Append("  \"scene_path\": \"").Append(ScenePath).Append("\",\n");
            sb.Append("  \"replay_object\": \"").Append(ReplayObjectName).Append("\",\n");
            sb.Append("  \"runs\": 20,\n");

            if (numbers.HasValue)
            {
                ReplayNumbers n = numbers.Value;
                sb.Append("  \"consistent\": ").Append(Bool(n.Consistent)).Append(",\n");
                sb.Append("  \"coverage_pass\": ").Append(Bool(n.CoveragePass)).Append(",\n");
                sb.Append("  \"coverage_perfect\": ").Append(Bool(n.CoveragePerfect)).Append(",\n");
                sb.Append("  \"verdict\": \"").Append(Escape(n.Verdict)).Append("\",\n");
                sb.Append("  \"coverage\": ").Append(Num(n.Coverage)).Append(",\n");
                sb.Append("  \"iou\": ").Append(Num(n.Iou)).Append(",\n");
                sb.Append("  \"negative_control_live\": ").Append(Bool(n.GateLive)).Append(",\n");
                sb.Append("  \"nc_folded_iou\": ").Append(Num(n.NcFoldedIou)).Append(",\n");
                sb.Append("  \"nc_unfolded_iou\": ").Append(Num(n.NcUnfoldedIou)).Append(",\n");
                sb.Append("  \"nc_unfolded_coverage\": ").Append(Num(n.NcUnfoldedCov)).Append(",\n");
                sb.Append("  \"nc_wrongside_iou\": ").Append(Num(n.NcWrongSideIou)).Append(",\n");
                sb.Append("  \"min_ms\": ").Append(Num(n.MinMs)).Append(",\n");
                sb.Append("  \"p50_ms\": ").Append(Num(n.P50Ms)).Append(",\n");
                sb.Append("  \"max_ms\": ").Append(Num(n.MaxMs)).Append(",\n");
                sb.Append("  \"drawer_place\": ").Append(Bool(n.DrawerPlace)).Append(",\n");
                sb.Append("  \"drawer_reject\": ").Append(Bool(n.DrawerReject)).Append(",\n");
                sb.Append("  \"report\": \"").Append(Escape(n.Report)).Append("\"");
                if (error != null) sb.Append(",\n  \"error\": \"").Append(Escape(error.ToString())).Append("\"");
                sb.Append("\n");
            }
            else
            {
                sb.Append("  \"consistent\": false,\n");
                sb.Append("  \"coverage_pass\": false,\n");
                sb.Append("  \"coverage_perfect\": false,\n");
                sb.Append("  \"negative_control_live\": false,\n");
                sb.Append("  \"verdict\": \"NOT_RUN\",\n");
                sb.Append("  \"coverage\": -1.0,\n");
                sb.Append("  \"iou\": -1.0,\n");
                sb.Append("  \"min_ms\": -1.0,\n");
                sb.Append("  \"p50_ms\": -1.0,\n");
                sb.Append("  \"max_ms\": -1.0,\n");
                sb.Append("  \"drawer_place\": false,\n");
                sb.Append("  \"drawer_reject\": false,\n");
                sb.Append("  \"error\": \"").Append(Escape(error == null ? "unknown" : error.ToString())).Append("\"\n");
            }

            sb.Append("}\n");
            File.WriteAllText(path, sb.ToString(), new UTF8Encoding(false));
            Debug.Log("[FoldSpike] wrote " + path);
        }

        static string Bool(bool v) { return v ? "true" : "false"; }

        static string Num(double v)
        {
            return v.ToString("F4", CultureInfo.InvariantCulture);
        }

        static string Escape(string s)
        {
            if (string.IsNullOrEmpty(s)) return string.Empty;
            StringBuilder sb = new StringBuilder(s.Length + 16);
            for (int i = 0; i < s.Length; i++)
            {
                char c = s[i];
                switch (c)
                {
                    case '\\': sb.Append("\\\\"); break;
                    case '"': sb.Append("\\\""); break;
                    case '\n': sb.Append("\\n"); break;
                    case '\r': sb.Append("\\r"); break;
                    case '\t': sb.Append("\\t"); break;
                    default:
                        if (c < ' ') sb.Append(' ');
                        else sb.Append(c);
                        break;
                }
            }
            return sb.ToString();
        }

        static Material EnsureMaterial()
        {
            Material existing = AssetDatabase.LoadAssetAtPath<Material>(MaterialPath);
            if (existing != null) return existing;

            Shader shader = Shader.Find("Sprites/Default");
            if (shader == null)
            {
                Debug.LogWarning("[FoldSpike] Sprites/Default shader not found; scene renders without a material.");
                return null;
            }

            EnsureAssetFolder(MaterialDir);
            Material mat = new Material(shader);
            mat.name = "FoldPaper";
            AssetDatabase.CreateAsset(mat, MaterialPath);
            AssetDatabase.SaveAssets();
            return mat;
        }

        static void EnsureAssetFolder(string assetPath)
        {
            if (AssetDatabase.IsValidFolder(assetPath)) return;
            string normalized = assetPath.Replace('\\', '/');
            string parent = Path.GetDirectoryName(normalized);
            if (!string.IsNullOrEmpty(parent)) parent = parent.Replace('\\', '/');
            string leaf = Path.GetFileName(normalized);
            if (!string.IsNullOrEmpty(parent) && !AssetDatabase.IsValidFolder(parent)) EnsureAssetFolder(parent);
            AssetDatabase.CreateFolder(parent, leaf);
        }
    }
}
