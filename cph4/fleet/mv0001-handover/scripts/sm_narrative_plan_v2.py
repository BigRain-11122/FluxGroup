PUNCH = [1.0, 1.15, 1.30, 1.15]      # 第 n 次出现的推近倍率


def main():
    pool = {s["id"]: s for s in json.load(open(os.path.join(POOL_DIR, "SHOT-POOL.json"),
                                               encoding="utf-8"))["shots"]}
    mot = json.load(open(os.path.join(POOL_DIR, "SHOT-MOTION.json"), encoding="utf-8"))

    plan, warn, t = [], [], 0.0
    used = {}
    for sec, s0, s1, shots in SECTIONS:
        span = s1 - s0
        want = sum(d for _, d, _, _ in shots)
        if abs(want - span) > 0.05:
            # 按比例微调整段，保证时间轴严格对齐
            k = span / want
            shots = [(i, round(d * k, 3), l, n) for i, d, l, n in shots]
        for sid, d, line, note in shots:
            src = pool[sid]
            m = mot.get(sid, {})
            n = used.get(sid, 0)
            used[sid] = n + 1
            punch = PUNCH[min(n, len(PUNCH) - 1)]
            peak = float(m.get("peak_t", src["dur"] * 0.4))
            # 切入：首用取峰值前 0.35s；重演后移 1.2s（换一段动作）
            in_pt = peak - 0.35 + (1.2 * n)
            in_pt = max(0.0, min(in_pt, max(0.0, src["dur"] - d)))
            plan.append({
                "t0": round(t, 3), "t1": round(t + d, 3), "dur": d,
                "section": sec, "id": sid, "line": line, "note": note,
                "src": src["path"], "src_dur": src["dur"],
                "in_pt": round(in_pt, 3), "punch": punch,
                "w": src["w"], "h": src["h"],
            })
            if d > src["dur"]:
                warn.append("%s 目标 %.2fs > 源 %.2fs" % (sid, d, src["dur"]))
            t += d

    json.dump({"total_s": round(t, 3), "clips": len(plan), "sections": len(SECTIONS),
               "warnings": warn, "plan": plan},
              open(OUT, "w", encoding="utf-8"), ensure_ascii=False, indent=1)

    print("PLAN v2: %d 段 / %d 镜 / %.2fs" % (len(SECTIONS), len(plan), t))
    lens = [p["dur"] for p in plan]
    print("镜长: 均值 %.2f  最短 %.2f  最长 %.2f" % (sum(lens) / len(lens), min(lens), max(lens)))
    print("密度(每30s段均镜长):")
    for sec, s0, s1, _ in SECTIONS:
        seg = [p["dur"] for p in plan if p["section"] == sec]
        print("  %-18s %.2fs/镜 × %d" % (sec, sum(seg) / len(seg), len(seg)))
    print("重演统计:", {k: v for k, v in used.items() if v > 1})
    for w in warn:
        print("  ! " + w)


if __name__ == "__main__":
    main()
